"""
LAB | Agents that speak MCP fluently

Pipeline:
  docs/*.md -> docs_server.py (MCP, stdio) -> MultiServerMCPClient (langchain-mcp-adapters)
  -> MCP tools as LangChain tools + MCP resource as background context
  -> LangChain agent (gpt-4o-mini) -> answer -> grounding check -> lab_proof.md

Run:   python mcp_langchain.py
Needs: OPENAI_API_KEY in .env
"""
import asyncio
import json
import os
import re
import sys
from datetime import datetime
from pathlib import Path

from dotenv import load_dotenv
from langchain_mcp_adapters.client import MultiServerMCPClient
from langchain_openai import ChatOpenAI

try:  # LangChain >= 1.0
    from langchain.agents import create_agent

    def build_agent(llm, tools, system_prompt):
        return create_agent(llm, tools, system_prompt=system_prompt)

except ImportError:  # older LangChain: LangGraph prebuilt ReAct agent
    from langgraph.prebuilt import create_react_agent

    def build_agent(llm, tools, system_prompt):
        return create_react_agent(llm, tools, prompt=system_prompt)


HERE = Path(__file__).resolve().parent
SERVER = HERE / "docs_server.py"
PROOF = HERE / "lab_proof.md"
MODEL = os.getenv("OPENAI_MODEL", "gpt-4o-mini")
NOT_FOUND = "NOT IN SOURCES"

# The one query traced in lab_proof.md
MAIN_QUERY = (
    "Under our incident management policy, how fast must a major ICT incident be "
    "reported to the regulator, and who must approve the notification?"
)
# Failure probe: the answer is NOT in the documents
PROBE_QUERY = "What fine does the regulator impose if we report a major ICT incident late?"

SYSTEM_TEMPLATE = """You are a document analysis agent for internal policies.
You can only use the MCP tools (list_documents, search_documents, read_document) as your source.

Rules:
1. Always call a tool before answering. Never answer from your own general knowledge.
2. Prefer read_document on the relevant file so you see the full section.
3. In the answer, cite the file name and section number for every fact.
4. If the documents do not contain the answer, reply starting with "{not_found}" and say what is missing.

Background context from MCP resource docs://index:
{index}
"""


# ---------------------------------------------------------------- helpers
def text_of(content) -> str:
    """MCP tool output can be a string or a list of content blocks."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        return "\n".join(
            (c.get("text") or json.dumps(c)) if isinstance(c, dict) else str(c) for c in content
        )
    return str(content)


async def run_query(agent, query: str) -> dict:
    result = await agent.ainvoke({"messages": [{"role": "user", "content": query}]})
    calls, outputs = [], {}
    for m in result["messages"]:
        for tc in getattr(m, "tool_calls", None) or []:
            calls.append({"id": tc["id"], "name": tc["name"], "args": tc["args"]})
        if m.type == "tool":
            outputs[m.tool_call_id] = text_of(m.content)
    for c in calls:
        c["output"] = outputs.get(c["id"], "(no output captured)")
    return {"query": query, "calls": calls, "final": text_of(result["messages"][-1].content)}


def grounding_check(run: dict) -> list[tuple[str, bool, str]]:
    """Simple, inspectable checks that tie the answer to the tool evidence."""
    evidence = "\n".join(c["output"] for c in run["calls"])
    final = run["final"]
    checks = [("At least one MCP tool was called", bool(run["calls"]), f"{len(run['calls'])} call(s)")]

    files_read = {c["args"].get("filename") for c in run["calls"] if c["name"] == "read_document"}
    cited = set(re.findall(r"[\w-]+\.md", final))
    checks.append(
        (
            "Every cited file was actually read via read_document",
            bool(cited) and cited <= files_read,
            f"cited={sorted(cited)} read={sorted(f for f in files_read if f)}",
        )
    )

    numbers = sorted(set(re.findall(r"\d+(?:[.,]\d+)?", final)))
    for n in numbers:
        found = re.search(rf"(?<![\d.]){re.escape(n)}(?![\d])", evidence) is not None
        checks.append((f"Number '{n}' in answer appears in tool evidence", found, "supported" if found else "UNSUPPORTED"))
    return checks


def block(text: str, limit: int = 2500) -> str:
    text = text if len(text) <= limit else text[:limit] + "\n... (truncated)"
    return f"```\n{text}\n```"


# ---------------------------------------------------------------- proof file
def write_proof(tools, resources, main, checks, probe):
    L = []
    L.append("# LAB | Agents that speak MCP fluently - lab_proof.md\n")
    L.append(f"Generated by `mcp_langchain.py` on {datetime.now():%Y-%m-%d %H:%M} with model `{MODEL}`.\n")

    L.append("## 1. Code and workflow\n")
    L.append("| File | Role |\n|---|---|")
    L.append("| `docs/*.md` | Source documents (two fictional internal policies) |")
    L.append("| `docs_server.py` | Local MCP server (FastMCP, stdio): 3 tools + 1 resource |")
    L.append("| `mcp_langchain.py` | MCP client, LangChain agent, grounding check, writes this file |\n")
    L.append("```")
    L.append("docs/*.md -> docs_server.py (MCP stdio) -> MultiServerMCPClient.get_tools()")
    L.append("          -> LangChain agent (ChatOpenAI) -> tool calls -> final answer")
    L.append("          -> grounding check (answer vs tool evidence) -> lab_proof.md")
    L.append("```\n")
    L.append("Key code:\n")
    L.append("```python")
    L.append('client = MultiServerMCPClient({"docs": {"command": sys.executable,')
    L.append('                                        "args": ["docs_server.py"], "transport": "stdio"}})')
    L.append("tools = await client.get_tools()                      # MCP tools -> LangChain tools")
    L.append('async with client.session("docs") as s:               # MCP resource as context')
    L.append('    index = await s.read_resource("docs://index")')
    L.append("agent = create_agent(ChatOpenAI(model=MODEL), tools, system_prompt=...)")
    L.append("```\n")

    L.append("## 2. MCP connection evidence\n")
    L.append("Tools loaded into LangChain:\n")
    for t in tools:
        L.append(f"- `{t.name}`: {t.description}")
    L.append("\nResources:\n")
    for uri, txt in resources:
        L.append(f"`{uri}`\n{block(txt)}")

    L.append("\n## 3. Query\n")
    L.append(f"> {main['query']}\n")

    L.append("## 4. Tool evidence (what the agent actually retrieved)\n")
    for i, c in enumerate(main["calls"], 1):
        L.append(f"**Call {i}: `{c['name']}({json.dumps(c['args'])})`**\n")
        L.append(block(c["output"]) + "\n")

    L.append("## 5. Final output\n")
    L.append(block(main["final"]) + "\n")

    L.append("## 6. Verify: grounding check\n")
    L.append("| Check | Result | Detail |\n|---|---|---|")
    for name, ok, detail in checks:
        L.append(f"| {name} | {'PASS' if ok else 'FAIL'} | {detail} |")
    L.append("")

    L.append("## 7. Failure / limitation\n")
    L.append(f"**Failure probe** (answer is not in the documents):\n\n> {probe['query']}\n")
    L.append(f"Tools called: {', '.join(c['name'] for c in probe['calls']) or 'none'}\n")
    L.append(block(probe["final"]) + "\n")
    declined = probe["final"].strip().upper().startswith(NOT_FOUND)
    L.append(
        f"Result: **{'PASS - agent declined instead of guessing' if declined else 'FAIL - agent gave an answer the sources do not support'}**\n"
    )
    L.append("**Where could the system produce a plausible but unsupported answer?**\n")
    L.append(
        "- *Parametric knowledge leak:* the rule \"answer only from tools\" is only a prompt instruction. "
        "For a question like the probe, the model knows real-world regulation and can answer fluently "
        "even though no document supports it. Nothing in the agent loop enforces grounding; only the "
        "check after the run catches it."
    )
    L.append(
        "- *Keyword search misses:* `search_documents` is exact substring match. A user asking about an "
        "\"outage\" will not match \"incident\", so the agent may wrongly conclude the information is missing, "
        "or fill the gap itself."
    )
    L.append(
        "- *Weak verifier:* the grounding check only verifies numbers and cited file names against the tool "
        "evidence. A wrong role or a misread condition (e.g. mixing up the 4-hour and 24-hour deadlines) "
        "could still pass. Next improvement: claim-level check (each sentence must match a quoted source line)."
    )
    PROOF.write_text("\n".join(L), encoding="utf-8")


# ---------------------------------------------------------------- main
async def main():
    # Step 1: environment
    load_dotenv(HERE / ".env")
    if not os.getenv("OPENAI_API_KEY"):
        sys.exit("OPENAI_API_KEY not found. Create a .env file with OPENAI_API_KEY=...")
    print("[1] OpenAI API key loaded")

    # Step 2: connect to MCP server
    client = MultiServerMCPClient(
        {"docs": {"command": sys.executable, "args": [str(SERVER)], "transport": "stdio"}}
    )

    # Step 3: MCP tools -> LangChain tools
    tools = await client.get_tools()
    print("[2-3] MCP tools loaded:", [t.name for t in tools])

    # Step 5: MCP resources as context
    resources = []
    async with client.session("docs") as session:
        listed = await session.list_resources()
        for r in listed.resources:
            read = await session.read_resource(r.uri)
            resources.append((str(r.uri), "\n".join(getattr(c, "text", "") for c in read.contents)))
    print("[5] MCP resources:", [u for u, _ in resources])
    index_text = next((t for u, t in resources if u == "docs://index"), "(no index)")

    # Step 4/6: agent
    llm = ChatOpenAI(model=MODEL)  # no temperature: some OpenAI models reject it
    agent = build_agent(llm, tools, SYSTEM_TEMPLATE.format(not_found=NOT_FOUND, index=index_text))

    main_run = await run_query(agent, MAIN_QUERY)
    print("\n[4] QUERY:", MAIN_QUERY)
    for c in main_run["calls"]:
        print(f"    tool -> {c['name']}({c['args']})")
    print("    ANSWER:", main_run["final"])

    checks = grounding_check(main_run)
    print("\n[VERIFY]")
    for name, ok, detail in checks:
        print(f"    {'PASS' if ok else 'FAIL'}  {name}  ({detail})")

    probe_run = await run_query(agent, PROBE_QUERY)
    print("\n[FAILURE PROBE]", PROBE_QUERY)
    print("    ANSWER:", probe_run["final"])

    write_proof(tools, resources, main_run, checks, probe_run)
    print(f"\nWrote {PROOF.name}")
    # MCP sessions are opened per call by langchain-mcp-adapters (>=0.1) and closed automatically.


if __name__ == "__main__":
    asyncio.run(main())
